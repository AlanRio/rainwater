#!/usr/bin/env python3
"""Rebuild rainfall.js: daily rainfall for the house near Prayssac (Lot).

Two sources, aligned day by day so the page can switch between them:

  anglars  Météo-France rain gauge 46005001, Anglars-Juillac, 2.9 km from the house.
           Open data from data.gouv.fr ("Données climatologiques de base - quotidiennes").
           Each value is the 24 h total from 06:00 UTC that day to 06:00 UTC the next.
  era5     ERA5 reanalysis (a weather model, ~28 km grid) from the Open-Meteo archive,
           kept as an independent cross-check.

Usage:
    python scripts/update_rainfall.py               # 1994-01-01 to the latest common day
    python scripts/update_rainfall.py --start 2000-01-01

Uses only the Python standard library, so it runs as-is in GitHub Actions.
"""
import argparse
import csv
import datetime as dt
import gzip
import io
import json
import pathlib
import re
import urllib.parse
import urllib.request

OUT = pathlib.Path(__file__).resolve().parent.parent / "rainfall.js"

STATION = "46005001"
STATION_NAME = "Anglars-Juillac"
DATASET = "6569b51ae64326786e4e8e1a"  # Météo-France daily climatological data on data.gouv.fr
DEPT_FILE = re.compile(r"QUOT_departement_46_periode_(?!avant).*_RR-T-Vent$")

LAT, LON = 44.512, 1.188  # Prayssac
ERA5_LAG_DAYS = 6         # ERA5 on Open-Meteo trails real time by about 5 days


def get(url, timeout=180):
    req = urllib.request.Request(url, headers={"User-Agent": "rainwater-simulator"})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return resp.read()


def fetch_gauge():
    """Return {date: mm} for the Anglars gauge, from every department-46 daily file."""
    meta = json.loads(get(f"https://www.data.gouv.fr/api/1/datasets/{DATASET}/"))
    urls = [r["url"] for r in meta["resources"] if DEPT_FILE.match(r["title"])]
    if not urls:
        raise SystemExit("No department 46 daily files found on data.gouv.fr")
    rain = {}
    for url in urls:
        text = gzip.decompress(get(url)).decode("latin-1")
        for row in csv.DictReader(io.StringIO(text), delimiter=";"):
            if row["NUM_POSTE"] == STATION and row["RR"] != "":
                d = row["AAAAMMJJ"]
                rain[dt.date(int(d[:4]), int(d[4:6]), int(d[6:]))] = float(row["RR"])
    return rain


def fetch_era5(start, end):
    query = urllib.parse.urlencode({
        "latitude": LAT, "longitude": LON,
        "start_date": start.isoformat(), "end_date": end.isoformat(),
        "daily": "precipitation_sum", "timezone": "Europe/Paris", "models": "era5",
    })
    daily = json.loads(get(f"https://archive-api.open-meteo.com/v1/archive?{query}"))["daily"]
    return {dt.date.fromisoformat(t): v for t, v in zip(daily["time"], daily["precipitation_sum"]) if v is not None}


def fmt(values, start):
    """One line per year with a comment, so a data refresh only changes the last line."""
    lines, year, row = [], None, []
    for i, v in enumerate(values):
        y = (start + dt.timedelta(i)).year
        if y != year:
            if row:
                lines.append(f"      // {year}\n      " + ",".join(row) + ",")
            year, row = y, []
        row.append(f"{round(v, 1):g}")
    lines.append(f"      // {year}\n      " + ",".join(row) + ",")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description="Rebuild rainfall.js from Météo-France and Open-Meteo.")
    ap.add_argument("--start", default="1994-01-01", help="first day (the gauge is complete from 1994)")
    args = ap.parse_args()
    start = dt.date.fromisoformat(args.start)

    gauge = fetch_gauge()
    era5 = fetch_era5(start, dt.date.today() - dt.timedelta(days=ERA5_LAG_DAYS))
    end = min(max(gauge), max(era5))
    days = [start + dt.timedelta(i) for i in range((end - start).days + 1)]

    missing_era5 = [d for d in days if d not in era5]
    if missing_era5:
        raise SystemExit(f"ERA5 is missing {len(missing_era5)} days (first {missing_era5[0]}); not writing.")
    # Any gauge gap is filled with the ERA5 value for that day, and counted.
    filled = [d for d in days if d not in gauge]
    gauge_mm = [gauge.get(d, era5[d]) for d in days]
    era5_mm = [era5[d] for d in days]

    OUT.write_text(
        f"// Generated by scripts/update_rainfall.py on {dt.date.today().isoformat()}. Do not edit by hand.\n"
        "// Daily rainfall in mm for the house near Prayssac (Lot), one array per source, aligned by day.\n"
        "window.RAINFALL = {\n"
        f'  updated: "{dt.date.today().isoformat()}",\n'
        f'  start: "{start.isoformat()}",\n'
        f'  end: "{end.isoformat()}",\n'
        "  sources: {\n"
        "    anglars: {\n"
        f'      name: "Météo-France rain gauge, {STATION_NAME} (station {STATION})",\n'
        '      short: "Anglars rain gauge",\n'
        f"      filled: {len(filled)},\n"
        "      mm: [\n"
        f"{fmt(gauge_mm, start)}\n"
        "      ]\n"
        "    },\n"
        "    era5: {\n"
        f'      name: "ERA5 weather model via Open-Meteo, {LAT}N {LON}E",\n'
        '      short: "ERA5 weather model",\n'
        "      filled: 0,\n"
        "      mm: [\n"
        f"{fmt(era5_mm, start)}\n"
        "      ]\n"
        "    }\n"
        "  }\n"
        "};\n",
        encoding="utf-8", newline="\n",
    )
    print(f"Wrote {OUT.name}: {start} to {end}, {len(days)} days; "
          f"{len(filled)} gauge gaps filled from ERA5" + (f" (first {filled[0]})" if filled else ""))
    for y in range(start.year, end.year + 1):
        g = sum(v for d, v in zip(days, gauge_mm) if d.year == y)
        e = sum(v for d, v in zip(days, era5_mm) if d.year == y)
        print(f"  {y}: gauge {g:6.0f} mm   ERA5 {e:6.0f} mm")


if __name__ == "__main__":
    main()
